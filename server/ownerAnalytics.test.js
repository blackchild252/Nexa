"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { DatabaseSync } = require("node:sqlite");
const { buildOwnerAnalytics, toCsv } = require("./ownerAnalytics");
function fixture() {
  const db = new DatabaseSync(":memory:");
  db.exec(`
    CREATE TABLE users(id TEXT, email TEXT, createdAt TEXT);
    CREATE TABLE mall_orders(id TEXT,total REAL,currency TEXT,createdAt TEXT,userId TEXT,status TEXT);
    CREATE TABLE mall_refunds(id TEXT,amount REAL,currency TEXT,createdAt TEXT,status TEXT);
    CREATE TABLE mall_checkout_disputes(id TEXT,createdAt TEXT,status TEXT);
    CREATE TABLE wallet_transactions(id TEXT,userId TEXT,createdAt TEXT,status TEXT,amountMinor INTEGER,currency TEXT);
    CREATE TABLE mall_payment_events(eventKey TEXT,receivedAt TEXT,outcome TEXT);
    CREATE TABLE ai_workflows(id TEXT,userId TEXT,createdAt TEXT);
    CREATE TABLE ai_workflow_runs(id TEXT,userId TEXT,createdAt TEXT);
    CREATE TABLE ai_dami_audit_events(id TEXT,userId TEXT,createdAt TEXT);
    CREATE TABLE social_reports(id TEXT,createdAt TEXT);
    CREATE TABLE yaayz_social_posts(id TEXT,authorId TEXT,createdAt TEXT);
    CREATE TABLE dm_messages(id TEXT,senderId TEXT,createdAt TEXT,body TEXT);
    CREATE TABLE customer_care_threads(id TEXT,createdAt TEXT,status TEXT);
    CREATE TABLE admin_work(id TEXT,createdAt TEXT,status TEXT);
    CREATE TABLE admin_audit(id TEXT,createdAt TEXT);
    CREATE TABLE notification_events(id TEXT,userId TEXT,createdAt TEXT);
  `);
  const now = "2026-10-08T10:00:00.000Z";
  db.prepare("INSERT INTO users VALUES(?,?,?)").run("u1", "private@example.test", now);
  db.prepare("INSERT INTO users VALUES(?,?,?)").run("u2", "hidden@example.test", "2026-09-01T10:00:00.000Z");
  db.prepare("INSERT INTO mall_orders VALUES(?,?,?,?,?,?)").run("o1", 500, "NGN", now, "u1", "paid");
  db.prepare("INSERT INTO mall_orders VALUES(?,?,?,?,?,?)").run("o2", 100, "USD", now, "u2", "placed");
  db.prepare("INSERT INTO mall_refunds VALUES(?,?,?,?,?)").run("r1", 50, "NGN", now, "completed");
  db.prepare("INSERT INTO wallet_transactions VALUES(?,?,?,?,?,?)").run("w1", "u1", now, "failed", 500, "NGN");
  db.prepare("INSERT INTO wallet_transactions VALUES(?,?,?,?,?,?)").run("w2", "u2", now, "completed", 500, "NGN");
  db.prepare("INSERT INTO mall_payment_events VALUES(?,?,?)").run("p1", now, "failed");
  db.prepare("INSERT INTO mall_payment_events VALUES(?,?,?)").run("p2", now, "received");
  db.prepare("INSERT INTO ai_workflow_runs VALUES(?,?,?)").run("run1", "u1", now);
  db.prepare("INSERT INTO dm_messages VALUES(?,?,?,?)").run("m1", "u2", now, "private message body");
  db.prepare("INSERT INTO yaayz_social_posts VALUES(?,?,?)").run("s1", "u1", now);
  db.prepare("INSERT INTO customer_care_threads VALUES(?,?,?)").run("c1", now, "waiting");
  db.prepare("INSERT INTO admin_work VALUES(?,?,?)").run("a1", now, "assigned");
  return db;
}
test("owner analytics computes source-backed aggregate metrics and never returns member identity", () => {
  const db = fixture();
  const report = buildOwnerAnalytics(db, { now: new Date("2026-10-09T00:00:00.000Z"), windowDays: 30 });
  assert.equal(report.metrics.usersTotal.value, 2);
  assert.equal(report.metrics.orders.value, 2);
  assert.deepEqual(report.metrics.gmv.value, { NGN: 500, USD: 100 });
  assert.deepEqual(report.metrics.refundAmount.value, { NGN: 50 });
  assert.equal(report.metrics.walletFailed.value, 1);
  assert.equal(report.metrics.failedPayments.value, 1);
  assert.equal(report.metrics.customerCare.value, 1);
  assert.equal(report.metrics.staffWork.value, 1);
  assert.equal(report.metrics.dau.value, 2);
  assert.equal(report.metrics.signupConversion.available, false);
  assert.equal(report.metrics.retention.available, false);
  const serialized = JSON.stringify(report);
  assert.equal(serialized.includes("private@example.test"), false);
  assert.equal(serialized.includes("private message body"), false);
  assert.equal(report.export.piiIncluded, false);
  db.close();
});
test("owner analytics bounds the requested window and CSV exports aggregate fields only", () => {
  const db = fixture();
  const report = buildOwnerAnalytics(db, { now: new Date("2026-10-09T00:00:00.000Z"), windowDays: 999 });
  assert.equal(report.windowDays, 30);
  const csv = toCsv(report);
  assert.match(csv, /"metric","value","available","source","reason"/);
  assert.match(csv, /gmv/);
  assert.doesNotMatch(csv, /private@example\.test|private message body|password|userId/);
  db.close();
});
test("owner analytics marks missing canonical sources unavailable instead of fabricating zero", () => {
  const db = new DatabaseSync(":memory:");
  const report = buildOwnerAnalytics(db, { now: new Date("2026-10-09T00:00:00.000Z"), windowDays: 7 });
  assert.equal(report.metrics.usersTotal.available, false);
  assert.equal(report.metrics.orders.available, false);
  assert.equal(report.metrics.gmv.available, false);
  assert.equal(report.metrics.dau.available, false);
  assert.equal(report.windowDays, 7);
  db.close();
});
