"use strict";
const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const p=require("./v5_75_0_external_navigation");
const root=path.join(__dirname,"..");
const results=[];
function check(name,fn){test(name,()=>{fn();results.push(true);});}
check("M1225 external URL policy exists",()=>assert.equal(p.MILESTONES.length,25));
check("M1226 HTTPS required",()=>assert.equal(p.parseExternalUrl("http://example.com").ok,false));
check("M1227 blocked schemes",()=>assert.equal(p.parseExternalUrl("javascript:alert(1)").ok,false));
check("M1228 hostname normalized",()=>assert.equal(p.parseExternalUrl("https://Example.COM./a").hostname,"example.com"));
check("M1229 Paystack allowlist",()=>assert.equal(p.paymentUrl("https://checkout.paystack.com/pay/x").ok,true));
check("M1230 Google allowlist",()=>assert.equal(p.googleUrl("https://accounts.google.com/o/oauth2/auth").ok,true));
check("M1231 ad target HTTPS",()=>assert.equal(p.adTargetUrl("https://advertiser.example/path").ok,true));
check("M1232 ad image HTTPS",()=>assert.equal(p.adImageUrl("https://cdn.example/a.png").ok,true));
check("M1233 URL length bounded",()=>assert.equal(p.parseExternalUrl("https://example.com/"+"x".repeat(2100)).ok,false));
check("M1234 credentials rejected",()=>assert.equal(p.parseExternalUrl("https://u:p@example.com").ok,false));
check("M1235 userinfo rejected",()=>assert.equal(p.parseExternalUrl("https://user@example.com").ok,false));
check("M1236 fragments stripped",()=>assert.equal(p.parseExternalUrl("https://example.com/a#secret").url,"https://example.com/a"));
check("M1237 javascript rejected",()=>assert.equal(p.parseExternalUrl("javascript:location='https://evil.example'").reason,"blocked_protocol"));
check("M1238 data rejected",()=>assert.equal(p.parseExternalUrl("data:text/html,x").reason,"blocked_protocol"));
check("M1239 file rejected",()=>assert.equal(p.parseExternalUrl("file:///etc/passwd").reason,"blocked_protocol"));
check("M1240 localhost rejected",()=>assert.equal(p.parseExternalUrl("https://localhost/a").reason,"private_host_forbidden"));
check("M1241 private host rejected",()=>assert.equal(p.parseExternalUrl("https://192.168.1.10/a").reason,"private_host_forbidden"));
check("M1242 payment origin restricted",()=>assert.equal(p.paymentUrl("https://evil.example/pay").ok,false));
check("M1243 audit helper exists",()=>assert.equal(typeof p.allowlistedUrl,"function"));
check("M1244 safe error contract",()=>assert.equal(p.safeNavigationError("host_not_allowlisted").code,"EXTERNAL_NAVIGATION_BLOCKED"));
check("M1245 client helper file exists",()=>assert.ok(fs.existsSync(path.join(root,"src","safeExternalNavigation.ts"))));
check("M1246 payment integration uses helper",()=>assert.match(fs.readFileSync(path.join(root,"src","safeExternalNavigation.ts"),"utf8"),/openPaymentUrl/));
check("M1247 Yaayz integration uses helper",()=>assert.match(fs.readFileSync(path.join(root,"src","YaayzScreen.tsx"),"utf8"),/openExternalUrl/));
check("M1248 certification requires 25",()=>assert.equal(p.certification(Array(25).fill(true)).ok,true));
check("M1249 cumulative certification",()=>assert.equal(p.certification(Array(24).fill(true)).ok,false));
test("B115 cumulative release files remain present",()=>{assert.ok(fs.existsSync(path.join(root,"server","v5_74_0_rate_limit_integrity.contract.test.js")));});
