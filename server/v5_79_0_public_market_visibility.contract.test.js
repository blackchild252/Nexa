'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const policy = require('./v5_79_0_public_market_visibility');
const index = fs.readFileSync(path.join(__dirname, 'index.js'), 'utf8');

test('M1325 bounded product ids', () => assert.equal(policy.normalizeId('  mp_1 '), 'mp_1'));
test('M1326 rejects empty ids', () => assert.equal(policy.normalizeId(''), null));
test('M1327 rejects overlong ids', () => assert.equal(policy.normalizeId('x'.repeat(81)), null));
test('M1328 product query requires active product', () => assert.match(policy.publicProductQuery('x').where, /p\.active = 1/));
test('M1329 product query requires active vendor', () => assert.match(policy.publicProductQuery('x').where, /v\.status/));
test('M1330 vendor query requires active vendor', () => assert.match(policy.publicVendorQuery('v').where, /v\.status/));
test('M1331 public cache is bounded', () => assert.match(policy.PUBLIC_CACHE_CONTROL, /max-age=300/));
test('M1332 public cache must revalidate', () => assert.match(policy.PUBLIC_CACHE_CONTROL, /must-revalidate/));
test('M1333 private cache is no-store', () => assert.equal(policy.PRIVATE_CACHE_CONTROL, 'no-store'));
test('M1334 public image headers are mutable-cache safe', () => assert.equal(policy.publicImageHeaders({publicListing:true})['Cache-Control'], policy.PUBLIC_CACHE_CONTROL));
test('M1335 non-public image headers are no-store', () => assert.equal(policy.publicImageHeaders({publicListing:false})['Cache-Control'], 'no-store'));
test('M1336 image content type remains nosniff', () => assert.equal(policy.publicImageHeaders({publicListing:true})['X-Content-Type-Options'], 'nosniff'));
test('M1337 policy requires active products', () => assert.equal(policy.visibilityContract().activeProductRequired, true));
test('M1338 policy requires active vendors', () => assert.equal(policy.visibilityContract().activeVendorRequired, true));
test('M1339 retired assets are not public', () => assert.equal(policy.visibilityContract().retiredAssetsNotPublic, true));
test('M1340 asset cache is mutable', () => assert.equal(policy.visibilityContract().mutableAssetCache, true));
test('M1341 non-public assets are no-store', () => assert.equal(policy.visibilityContract().noStoreForNonPublic, true));
test('M1342 product detail uses visibility policy', () => assert.match(index, /publicMarketVisibility\.publicProductQuery/));
test('M1343 product image uses visibility policy', () => assert.match(index, /publicMarketVisibility\.publicProductQuery/));
test('M1344 public share page uses visibility policy', () => assert.match(index, /publicMarketVisibility\.publicProductQuery/));
test('M1345 public shop uses vendor visibility policy', () => assert.match(index, /publicMarketVisibility\.publicVendorQuery/));
test('M1346 image cache no longer immutable', () => assert.doesNotMatch(index, /Cache-Control.*immutable/));
test('M1347 image endpoint uses bounded id', () => assert.match(index, /publicMarketVisibility\.normalizeId\(req\.params\.id\)/));
test('M1348 visibility module is loaded once', () => assert.match(index, /require\("\.\/v5_79_0_public_market_visibility"\)/));
test('M1349 cumulative certification marker exists', () => assert.match(index, /PUBLIC_MARKET_VISIBILITY_CERTIFIED/));
